import { mkdir, readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
import { WorkspaceTypertGenerator } from '@deepseek-ai/dsh-typert-generator';
const root=new URL('../',import.meta.url).pathname;
const generated=new WorkspaceTypertGenerator(root).generate(['hanaworlds-workshop-image-panel'],['host']);
if(generated.length!==1||!generated[0].remote)throw Error('Panel strict Remote contribution missing');
await mkdir(new URL('../lib/',import.meta.url),{recursive:true});
await writeFile(new URL('../lib/typert.host.js',import.meta.url),generated[0].js);
await writeFile(new URL('../lib/typert.host.d.ts',import.meta.url),generated[0].dts);
await writeFile(new URL('../lib/typert.remote-client.js',import.meta.url),generated[0].remote.js);
await writeFile(new URL('../lib/typert.remote-client.d.ts',import.meta.url),generated[0].remote.dts);
const source=await readFile(new URL('../panel/src/index.ts',import.meta.url),'utf8');
const output=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext},fileName:'panel-host.ts'});
await writeFile(new URL('../lib/panel-host.mjs',import.meta.url),output.outputText);
console.log(JSON.stringify({generator:'@deepseek-ai/dsh-typert-generator@0.2.0-rc.2',strictRemote:true,outputs:5}));
